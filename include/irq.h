#ifndef IRQ_H
#define IRQ_H

#include <stdint.h>

/* Диспетчер прерываний GIC (CPU0). Ассемблерный обработчик в boot.s
 * сохраняет контекст на IRQ-стеке (sp_irq) и вызывает irq_c_dispatch()
 * БЕЗ переключения в SVC — всё выполняется в IRQ-режиме; I-бит на время
 * обработки выставлен аппаратно, вложенность невозможна.
 * Диспетчер читает активную линию из GICC_IAR, вызывает зарегистрированный
 * обработчик и подтверждает окончание через GICC_EOIR.
 *
 * Обработчик должен быть быстрым; если нужен длительный разбор — снять
 * pending в периферии и отложить основную работу в фоновый цикл.
 */

/* Тип обработчика. param — значение, переданное при регистрации. */
typedef void (*irq_handler_t)(uint32_t irq, void *param);

/* Зарегистрировать обработчик для номера линии GIC (номер из таблицы
 * прерываний даташита; для H3 Timer0 = 50). При повторной регистрации
 * заменяет предыдущий. Возвращает 0 при успехе, -1 вне диапазона. */
int irq_register(uint32_t irq, irq_handler_t h, void *param);

/* Разрешить/запретить конкретный IRQ в GIC. */
void irq_enable(uint32_t irq);
void irq_disable(uint32_t irq);

/* Глобальный I-бит (CPSR). disable() возвращает прежнее состояние,
 * restore(was) восстанавливает — удобно для критической секции. */
uint32_t irq_global_disable(void);
void     irq_global_restore(uint32_t was);
void     irq_global_enable(void);

/* Внутренний диспетчер, вызывается из boot.s (не для пользователя). */
void irq_c_dispatch(void);

#endif /* IRQ_H */
