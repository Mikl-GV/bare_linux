#ifndef I2S_H
#define I2S_H

#include <stdint.h>

/* I2S0 -> MAX98357A на Allwinner H3 (sun8i).
 * Формат: 48 кГц стерео 16 бит, буфер 32-битных слов на FIFO.
 * Основано на даташите H3 (8.6) и Linux-драйвере sun8i-h3-i2s.
 *
 * Два циклических LLI по половине буфера каждый; DMA с отключёнными
 * прерываниями (IRQ_EN=0), поэтому pending-флаги не накапливаются и не
 * блокируют канал — отдельный вызов i2s_tick() не нужен (даташит 4.11.4.1-7).
 */

/* Инициализировать PLL/такт I2S0, пины, настроить I2S0 и DMA-канал.
 * Дескрипторы и буфер заполняются позже через i2s_play_freq().
 * Возвращает 0 при успехе. */
int  i2s_init(void);

/* Заполнить DMA-буфер синусом частоты freq (Гц) и запустить DMA. */
void i2s_play_freq(int freq);

/* Остановить DMA и заглушить усилитель (тишина). */
void i2s_stop(void);

/* Заглушить (PA10=0). */
void i2s_mute(int mute);

#endif /* I2S_H */