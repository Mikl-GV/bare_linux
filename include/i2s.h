#ifndef I2S_H
#define I2S_H

#include <stdint.h>

/* I2S0 -> MAX98357A (Allwinner H3, sun8i).
 *
 * Формат: 48 кГц стерео 16 бит; отсчёт лежит в СТАРШИХ 16 битах 32-битного
 * слова FIFO, пара — [L<<16][R<<16] (TXIM=0, SW=32, SR=16, MODE=Left+offset).
 * Один стереокадр = 8 байт (два 32-битных слова).
 *
 * Вывод потоковый: приложение пишет PCM в кольцевой буфер через i2s_write(),
 * DMAC играет кольцо непрерывно. Кольцо разбито на равные периоды (по одному
 * LLI-дескриптору на период); позиция чтения берётся из CUR_SRC DMA-канала,
 * прерывания DMA не используются.
 */

/* Кольцо по умолчанию: 4 периода по 1024 кадра = 32 КБ (85 мс при 48 кГц),
 * один период = 21.3 мс. Меняется только вместе с linker.ld (.dma_buf >= 32 КБ). */
#define I2S_PERIOD_FRAMES   1024u
#define I2S_PERIODS         4u

/* Инициализировать PLL/такт I2S0, пины, I2S0 и кольцо DMA (буфер не заполняется).
 * Возвращает 0 при успехе. */
int  i2s_init(void);

/* Частота дискретизации: 48000 (PLL 24.576 МГц) или 44100 (PLL 22.5792 МГц).
   0 при успехе, -1 для неподдерживаемой частоты. Смена частоты перезапускает
   вывод (кольцо обнуляется) — данные заливать после вызова. */
int  i2s_set_rate(unsigned fs);

/* Запустить/остановить вывод. i2s_start() обнуляет указатели кольца, поэтому
 * заполнять кольцо нужно ПОСЛЕ старта. */
void i2s_start(void);
void i2s_stop(void);

/* Записать кадры (interleaved L,R, int16). Возвращает число принятых кадров
 * (может быть меньше frames, если в кольце мало места). 0 — ничего не принято. */
int  i2s_write(const int16_t *pcm, unsigned frames);

/* Свободно / занято кадров в кольце. */
unsigned i2s_space(void);
unsigned i2s_buffered(void);

/* Заглушить усилитель (PA10). */
void i2s_mute(int mute);

/* Тестовый тон: заполняет кольцо целым числом периодов синуса и запускает вывод
 * (совместимость с UI тонального теста). */
void i2s_play_freq(int freq);

#endif /* I2S_H */
