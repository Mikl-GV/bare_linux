#ifndef MEM_H
#define MEM_H

#include <stdint.h>

/* Динамическая память для слоёв эмуляторов (H3, 512 МБ DRAM).
 *
 * Предварительные расчёты бюджета (2026-10-23, зафиксировано как
 * ПРЕДВАРИТЕЛЬНЫЕ — уточняются при первом реальном эмуляторе):
 *
 *   RAM общая                   0x40000000..0x60000000  (512 МБ)
 *   [0x40000000.._end)          образ (код+данные+bss), сейчас ~116 КБ
 *   [.., 0x41000000)            запас / служебное (почта, разделяемые буферы)
 *   HEAP_START..HEAP_END        КУЧА эмулятора (динамика .bss/.data ядра)
 *   ROM_START..ROM_END          ЗОНА РОМА (игра грузится с SD целиком, макс 128 МБ)
 *   0x60000000 (вниз)           стек (растёт вниз от верха DRAM)
 *
 *  Между кучей и ROM-зоной — ЗАПАС (gap), чтобы кучу+BSS не разносило
 *  (в прошлом разрастались >50 МБ). Куча и ROM не пересекаются.
 *
 * Аллокатор: простой first-fit по блокам (заголовок 8 байт), выделяет
 * только из кучи. ROM-зона — отдельная жёстко зарезервированная область
 * (выдаётся целиком под загрузку игры, free после выхода из эмулятора).
 */

/* ---- Бюджет (предварительный) ---- */
#define MEM_ROM_MAX_BYTES   (128u * 1024u * 1024u)   /* макс. размер игры */

/* Зоны (адреса DRAM). Уточняются автоматически по фактическому _end. */
extern uint32_t _end[];           /* из linker.ld — конец образа */
extern uint32_t _dma_buf_start[]; /* DMA-буфер звука (64 КБ) */
extern uint32_t _dma_buf_end[];
extern uint32_t _fb_hdmi_start[]; /* FB HDMI (2.4 МБ) */
extern uint32_t _fb_hdmi_end[];

/* Адреса зон: вычисляются mem_init(). */
extern uint32_t mem_heap_start;
extern uint32_t mem_heap_end;
extern uint32_t mem_rom_start;
extern uint32_t mem_rom_end;

/* Инициализация зон: от _end (выровненного) до стека с запасом.
 * size — желаемый размер КУЧИ (0 = авто ~256 МБ). */
void mem_init(uint32_t heap_size);

/* Выделить/освободить из кучи (first-fit; возвращает NULL при нехватке). */
void *mem_alloc(uint32_t size);
void  mem_free(void *p);
uint32_t mem_free_bytes(void);            /* свободно в куче */

/* ROM-зона: зарезервировать под игру (один активный пользователь).
 * Возвращает адрес или NULL; mem_rom_release() освобождает. */
void *mem_rom_reserve(void);
void  mem_rom_release(void);
uint32_t mem_rom_capacity(void);          /* доступный размер зоны */

#endif /* MEM_H */