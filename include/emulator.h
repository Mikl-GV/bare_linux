#ifndef EMULATOR_H
#define EMULATOR_H

#include <stdint.h>

/* Диспетчер слоёв эмуляторов на CPU0 (H3).
 *
 * Архитектура (согласовано с проектом):
 *  - эмуляторы пишутся как НЕЗАВИСИМЫЕ слои; за один запуск активен ТОЛЬКО
 *    один;
 *  - память динамическая и переиспользуемая: при старте слой берёт из кучи
 *    столько, сколько нужно; при выходе — освобождает;
 *  - ром грузится с SD в RAM (зона ROM) ЦЕЛИКОМ при старте;
 *  - выход из эмулятора — долгое нажатие START ~3 с;
 *  - WiFi для эмулятора «не существует» (слой активен только в меню).
 *
 * Диспетчер (emulator_run_by_id) вызывает ядро по системному id (systems.h);
 * если ядро не реализовано — возвращает код ошибки (меню покажет заглушку).
 */

/* Коды выхода: 0 = эмулятор завершён (пользователь вышел), <0 = ошибка. */
enum {
    EMU_OK          = 0,
    EMU_ERR_NO_CORE = -1,   /* ядро для системы не реализовано */
    EMU_ERR_ROM     = -2,   /* ром не загружен / нет доступа к SD */
    EMU_ERR_MEM     = -3,   /* не хватило памяти (куча/ROM-зона) */
};

/* Описание запускаемого слоя. */
struct emu_run {
    uint32_t rom_addr;      /* адрес рома в RAM (зона ROM) */
    uint32_t rom_size;      /* размер рома (байт) */
    uint32_t sys_id;        /* id системы из systems.h */
    void    *heap;          /* выделенная для слоя куча (от диспетчера) */
    uint32_t heap_size;
};

/* Прототип ядра: active loop эмулятора. Блокирующая; возвращает при выходе
 * (долгое нажатие START ~3 с или штатное завершение). */
typedef int (*emu_core_fn)(const struct emu_run *run);

/* Запустить эмулятор для системы sys_id (по id из systems.h).
 *  - резервирует ROM-зону, загружает ром (path из sys dir) — см. emu_load_rom;
 *  - резервирует кучу (emulator_heap_size);
 *  - вызывает ядро (emu_core_fn по таблице);
 *  - на выходе освобождает ROM-зону и кучу.
 * Возвращает код из emu_result / EMU_*. */
int emulator_run(uint32_t sys_id, const char *rom_path, uint32_t rom_size);

/* Загрузить ром с SD (FAT) в зону ROM целиком. Заполняет out_addr/out_size.
 * Возвращает 0 при успехе, EMU_ERR_ROM/MEM при ошибке. */
int emu_load_rom(const char *path, uint32_t *out_addr, uint32_t *out_size);

/* INTERNAL: зарегистрировать ядро для id системы. Вызывается слоем при
 * линковке (weak-таблица внутри emulator.c). После регистрации система
 * считается «реализованной», и меню подсвечивает её пункт как доступный. */
void emulator_register_core(uint32_t sys_id, emu_core_fn fn);

/* Внутренний флаг «ядро реализовано» для пунктов меню. НЕ вызывать из
 * прикладного кода — меню читает его через emulator_core_ready(). */
int emulator_core_registered(uint32_t sys_id);

/* Проверка «пользователь хочет выйти»: долгое нажатие START (~3 с).
 * Ядро вызывает в своём главном цикле (каждую итерацию). Возвращает 1,
 * если надо выйти (START удержан >= EMU_EXIT_HOLD_MS). */
int emu_check_exit(void);

/* Время удержания START для выхода (мс). */
#define EMU_EXIT_HOLD_MS  3000u

#endif /* EMULATOR_H */